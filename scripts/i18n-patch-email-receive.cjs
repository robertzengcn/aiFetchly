function objToJs(obj, indent) {
  const pad = "  ".repeat(indent);
  const inner = "  ".repeat(indent + 1);
  const lines = Object.keys(obj).map((k) => {
    const v = obj[k];
    const key = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
    if (v && typeof v === "object" && !Array.isArray(v)) {
      return `${inner}${key}: ${objToJs(v, indent + 1)},`;
    }
    return `${inner}${key}: ${JSON.stringify(v)},`;
  });
  return `{\n${lines.join("\n")}\n${pad}}`;
}

const FILES = ["en", "zh", "es", "fr", "de", "ja"];

for (const lang of FILES) {
  const file = path.join(LANG_DIR, `${lang}.ts`);
  let src = fs.readFileSync(file, "utf8");
  const dict = TRANSLATIONS[lang];

  // 1) Route keys: insert after the email_service_edit line.
  const routeExtrasJs = Object.keys(dict.routeExtras)
    .map((k) => `    ${k}: ${JSON.stringify(dict.routeExtras[k])},`)
    .join("\n");
  const routeMarker = "email_service_edit:";
  if (src.includes(routeMarker) && !src.includes(`    email_receive:`)) {
    const idx = src.indexOf(routeMarker);
    const lineEnd = src.indexOf("\n", idx);
    src = src.slice(0, lineEnd + 1) + routeExtrasJs + "\n" + src.slice(lineEnd + 1);
  }

  // 2) Namespaces: insert before the `emailservice: {` namespace (stable anchor).
  const nsMarker = "emailservice: {";
  if (src.includes(nsMarker) && !src.includes("emailReceive: {")) {
    const block =
      `emailReceive: ${objToJs(dict.emailReceive, 0)},\n` +
      `emailReply: ${objToJs(dict.emailReply, 0)},\n` +
      `emailAutoReplyAudit: ${objToJs(dict.emailAutoReplyAudit, 0)},\n  `;
    src = src.replace(nsMarker, block + nsMarker);
  }

  fs.writeFileSync(file, src, "utf8");
  console.log(`patched ${lang}.ts`);
}
